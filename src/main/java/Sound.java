public class Sound {
    public static void main(String[] args) {
        double dist;
        dist = 1100 * 7.2;
        System.out.println("Расстояние до места вспышки молнии " +
                "составляет " + dist + " футов");
        double new_dist;
        new_dist = dist / 2;
        System.out.println("Расстояние до места хлопка в ладоши " +
                "до объекта составляет " + new_dist + " футов");
    }
}
