// Вывод всех простых чисел в диапазоне от 2 до 100.
public class OnlySimpleNumbers {
    public static void main(String[] args) {
        // x — проверяемое число, y — его возможный делитель.
        int x, y;
        System.out.println("Простые числа от 2 до 100");

        // Перебираем все числа от 2 до 100 включительно.
        for (x = 2; x <= 100; x++) {
            // Счётчик делителей обнуляется для каждого нового x.
            int count = 0;

            // Проверяем все числа от x до 1: если x делится на y, значит y — делитель x.
            for (y = x; y > 0; y--) {
                if ((x % y) == 0) {
                    count++;
                }
            }

            // У простого числа ровно два делителя: 1 и оно само.
            if (count == 2) {
                System.out.print(x + " ");
            }
        }
    }
}

